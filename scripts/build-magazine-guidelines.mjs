#!/usr/bin/env node
/**
 * Builds packages/radar-adapters/src/ranking/data/magazines/guidelines.ts from
 * reviewed research files: one JSON array per file, each record holding facts
 * quoted from a magazine's own submission guidelines. Only facts whose quote
 * was found on the live page (verified: true) are kept.
 *
 *   node scripts/build-magazine-guidelines.mjs --checked-on=2026-10-04 research/*.json
 */
import { readFileSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const checkedOn = args.find((a) => a.startsWith("--checked-on="))?.split("=")[1];
const files = args.filter((a) => !a.startsWith("--"));
if (!checkedOn || !files.length) {
  console.error("Usage: build-magazine-guidelines.mjs --checked-on=YYYY-MM-DD <verified research files>");
  process.exit(1);
}

/** A closure counts only when the quote says publication stopped, not that a reading window shut. */
const CEASED =
  /\b(ceas\w*|final issue|last issue|no longer (publish\w*|be publish\w*|produc\w*)|stopped publish\w*|ended publication|shut(ting)? down|discontinu\w*|hiatus|pause[ds]? publication|will not (be )?publish\w*|closed (its|our) doors|farewell)\b/i;

const keep = (fact) => (fact?.verified ? fact : null);
const records = [];
for (const file of files) {
  for (const r of JSON.parse(readFileSync(file, "utf8"))) {
    const fee = keep(r.fee);
    const pay = keep(r.pay);
    const response = keep(r.response);
    const statusValue = r.status === "closed" || r.status === "hiatus" ? r.status : null;
    const status =
      statusValue && r.statusEvidence?.quote && CEASED.test(r.statusEvidence.quote)
        ? { value: statusValue, url: r.statusEvidence.url, quote: r.statusEvidence.quote }
        : null;
    if (!fee && !pay && !response && !status) continue;
    records.push({
      profileId: r.profileId,
      name: r.name,
      checkedOn,
      fee: fee ? { charges: fee.charges, amountUSD: fee.amountUSD ?? null, url: fee.url, quote: fee.quote } : null,
      pay: pay ? { kind: pay.kind, url: pay.url, quote: pay.quote } : null,
      response: response ? { band: response.band, url: response.url, quote: response.quote } : null,
      status,
    });
  }
}
records.sort((a, b) => a.name.localeCompare(b.name));

const out = new URL("../packages/radar-adapters/src/ranking/data/magazines/guidelines.ts", import.meta.url);
writeFileSync(
  out,
  `// Generated by scripts/build-magazine-guidelines.mjs from reviewed research.
// Each fact was quoted from the magazine's own submission guidelines and the
// quote was checked against the live page. Do not edit by hand.
import type { MagazineGuidelineRecord } from "../../live/guidelineFacts.js";

export const MAGAZINE_GUIDELINES: MagazineGuidelineRecord[] = ${JSON.stringify(records, null, 2)};
`,
);
const count = (key) => records.filter((r) => r[key]).length;
console.log(
  `${records.length} magazines: fee ${count("fee")}, pay ${count("pay")}, response ${count("response")}, closed or paused ${count("status")}`,
);
