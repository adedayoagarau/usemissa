// Bundles the guide articles in apps/web/content/guides (one <slug>.md body and
// one <slug>.meta.json each) into a single JSON module the site imports, so the
// pages never read the file system at request time.
//
//   node scripts/build-guide-articles.mjs          write the bundle
//   node scripts/build-guide-articles.mjs --check  fail if the bundle is stale
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';

const directory = path.join(process.cwd(), 'apps/web/content/guides');
const output = path.join(directory, 'articles.generated.json');

export function buildGuideBundle(dir = directory) {
  const slugs = readdirSync(dir)
    .filter((file) => file.endsWith('.md'))
    .map((file) => file.replace(/\.md$/u, ''))
    .sort();
  const articles = {};
  for (const slug of slugs) {
    const metaPath = path.join(dir, `${slug}.meta.json`);
    if (!existsSync(metaPath)) throw new Error(`Missing ${slug}.meta.json next to ${slug}.md`);
    const meta = JSON.parse(readFileSync(metaPath, 'utf8'));
    if (meta.slug !== slug) throw new Error(`${slug}.meta.json has slug "${meta.slug}"`);
    articles[slug] = { meta, body: readFileSync(path.join(dir, `${slug}.md`), 'utf8') };
  }
  return `${JSON.stringify({ note: 'Generated by scripts/build-guide-articles.mjs from the .md and .meta.json files beside it. Edit those, then run npm run guides:build.', articles }, null, 2)}\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const next = buildGuideBundle();
  if (process.argv.includes('--check')) {
    const current = existsSync(output) ? readFileSync(output, 'utf8') : '';
    if (current !== next) {
      console.error('apps/web/content/guides/articles.generated.json is out of date. Run npm run guides:build.');
      process.exit(1);
    }
    console.log('Guide article bundle is up to date.');
  } else {
    writeFileSync(output, next);
    console.log(`Wrote ${path.relative(process.cwd(), output)}.`);
  }
}
