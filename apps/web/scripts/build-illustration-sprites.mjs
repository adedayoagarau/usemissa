/**
 * Builds the SVG sprites the site references with <use href="…#id">, from
 * the compact exports of the Missa illustration library:
 *
 *   public/illustrations/library-v2/compact/{covers,scenes,spots}/*.svg
 *     -> public/illustrations/library-v2/covers.svg   (every call cover)
 *     -> public/illustrations/library-v2/homepage.svg (the homepage's scenes and spots)
 *     -> public/illustrations/library-v2/empty-states.svg (art for empty states)
 *     -> components/illustrations/library-v2.generated.ts (ids and viewBoxes)
 *
 * <use> keeps the page's CSS custom properties (--art-ink, --art-accent,
 * --art-background), so one cached file serves every colourway, and the art
 * stays out of the JavaScript bundle.
 *
 * Run from apps/web: node scripts/build-illustration-sprites.mjs
 */
import { promises as fs } from "node:fs";
import path from "node:path";

const webRoot = path.resolve(import.meta.dirname, "..");
const library = path.join(webRoot, "public/illustrations/library-v2");
const compact = path.join(library, "compact");

/**
 * What each sprite carries. Everything scales whole; a cover's tint fills the
 * rest of its card from CSS (missa-illustrations.module.css), so a 4:3 drawing
 * sits uncropped in a 16:9 card.
 */
const SPRITES = [
  { file: "covers.svg", group: "covers", names: "all" },
  {
    file: "homepage.svg",
    group: ["scenes", "spots"],
    names: ["hero", "after-find", "questions", "close", "tracker", "reminders", "portfolio"],
  },
  {
    file: "empty-states.svg",
    group: ["scenes", "spots"],
    names: ["searching", "reading", "making-work", "celebrate", "library", "studio-key", "inbox"],
  },
];

async function readArt(group, name) {
  const source = await fs.readFile(path.join(compact, group, `${name}.svg`), "utf8");
  const root = source.match(/<svg\b([^>]*)>([\s\S]*)<\/svg>\s*$/);
  if (!root) throw new Error(`${group}/${name}.svg has no <svg> root`);
  const viewBox = root[1].match(/viewBox="([^"]+)"/)?.[1];
  if (!viewBox) throw new Error(`${group}/${name}.svg has no viewBox`);
  if (/<script|\son[a-z]+=|<foreignObject|<image|href="http/i.test(root[2])) {
    throw new Error(`${group}/${name}.svg contains active or external content`);
  }
  return { viewBox, body: root[2].trim() };
}

const generated = {};
for (const sprite of SPRITES) {
  const groups = Array.isArray(sprite.group) ? sprite.group : [sprite.group];
  const symbols = [];
  for (const group of groups) {
    const available = (await fs.readdir(path.join(compact, group)))
      .filter((file) => file.endsWith(".svg"))
      .map((file) => file.slice(0, -4))
      .sort();
    const names =
      sprite.names === "all" ? available : sprite.names.filter((name) => available.includes(name));
    for (const name of names) {
      const { viewBox, body } = await readArt(group, name);
      const id = `${group.replace(/s$/, "")}-${name}`;
      symbols.push(`<symbol id="${id}" viewBox="${viewBox}">${body}</symbol>`);
      generated[id] = { sprite: sprite.file, viewBox };
    }
  }
  const out = `<svg xmlns="http://www.w3.org/2000/svg" aria-hidden="true">${symbols.join("")}</svg>\n`;
  await fs.writeFile(path.join(library, sprite.file), out);
  console.log(`${sprite.file}: ${symbols.length} symbols, ${(out.length / 1024).toFixed(1)} KB`);
}

const moduleSource = `// Generated by scripts/build-illustration-sprites.mjs. Do not edit by hand.

export const ILLUSTRATION_SPRITE_ROOT = "/illustrations/library-v2";

export const ILLUSTRATIONS = ${JSON.stringify(generated, null, 2)} as const;

export type IllustrationId = keyof typeof ILLUSTRATIONS;
`;
await fs.writeFile(
  path.join(webRoot, "components/illustrations/library-v2.generated.ts"),
  moduleSource,
);
console.log(`library-v2.generated.ts: ${Object.keys(generated).length} ids`);
