await history.getByRole('switch',{name:'Only named versions'}).click();
await page.keyboard.press('Escape');
await editor().fill('A quiet dawn. A changed ending.');
await expect(page.getByText('Saved to account',{exact:true})).toBeVisible();
await page.clock.runFor(20000);
const automaticCount=async()=>{const data=await(await page.request.get(base+`/api/me/writing/${originalId}/snapshots`)).json();return data.snapshots.filter(version=>!version.name).length};
await expect.poll(automaticCount).toBeGreaterThanOrEqual(1);
await page.clock.runFor(30000);
await expect.poll(automaticCount).toBeGreaterThanOrEqual(2);
const autoList=(await(await page.request.get(base+`/api/me/writing/${originalId}/snapshots`)).json()).snapshots.filter(version=>!version.name);
const autoVersion=(await(await page.request.get(base+`/api/me/writing/${originalId}/snapshots/${autoList[0].id}`)).json()).snapshot;
assert.match(autoVersion.body,/quiet dawn/);
