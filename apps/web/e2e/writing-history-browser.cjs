await openHistory();
await history.getByRole('button',{name:'Compare',exact:true}).first().click();
await expect(page.getByRole('dialog',{name:'Submission draft and now'})).toContainText('changed ending');
await page.keyboard.press('Escape');
await expect(history).toBeVisible();
await history.getByRole('button',{name:'Options for Submission draft'}).click();
await page.getByRole('menuitem',{name:'Restore as a copy…'}).click();
await page.getByRole('button',{name:'Open restored copy',exact:true}).click();
